import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { testDatabase, httpSession, actor } from './helpers.js';
test('discovery task API enforces session ACL, versions and idempotent replay after revocation', async (t) => {
    const { db, config, cleanup } = await testDatabase();
    t.after(cleanup);
    const h = await httpSession(db, config, ['recruiter']);
    t.after(() => h.app.close());
    const outsider = await actor(db, ['recruiter']);
    const job = (await db.query("INSERT INTO jobs(name) VALUES('自动化工程师') RETURNING id")).rows[0];
    const url = '/api/v4/sourcing/tasks', key = randomUUID(), body = { name: '社媒找人', jobId: job.id, sources: ['zhihu'], keywords: ['n8n'] };
    const call = (url: string, payload: any, k = randomUUID()) => h.app.inject({ method: 'POST', url, headers: { ...h.headers, 'idempotency-key': k }, payload });
    let res = await call(url, body, key);
    assert.equal(res.statusCode, 200, res.body);
    const task = res.json().data;
    res = await call(url, body, key);
    assert.equal(res.json().data.id, task.id);
    res = await call(url, { ...body, name: '不同' }, key);
    assert.equal(res.statusCode, 409);
    res = await call(`${url}/${task.id}/actions`, { version: 1, action: 'start' });
    assert.equal(res.statusCode, 200, res.body);
    res = await call(`${url}/${task.id}/actions`, { version: 1, action: 'pause' });
    assert.equal(res.statusCode, 409);
    await db.query('UPDATE discovery_tasks SET owner_id=$2 WHERE id=$1', [task.id, outsider.id]);
    res = await h.app.inject({ url: `${url}/${task.id}`, headers: h.headers });
    assert.equal(res.statusCode, 403);
    res = await call(`${url}/${task.id}/actions`, { version: 2, action: 'pause' });
    assert.equal(res.statusCode, 403);
    const q = await call(url + '/query', {});
    assert.equal(q.json().data.total, 0);
});
